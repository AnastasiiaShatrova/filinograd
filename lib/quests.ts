function userPrompt(loc: Location, type: TaskType): string {
  return `Локация: ${loc.name}. Персонаж: ${loc.character} — ${loc.characterDesc}. Место: ${loc.scene}.
Сюжетные зацепки: ${loc.hooks.join("; ")}.
Тип задания — ${type}: ${TASK_HINTS[type]}

Верни JSON в точности:
{"title":"название, 3–5 слов","story":"встреча и беда, 4–7 предложений","task":{"type":"${type}","text":"задание одним предложением, понятное и конкретное"},"ending":"чем всё закончилось, 2–3 предложения"}`;
}

function parseJson(raw: string): any {
  const m = raw.replace(/```/g, "").match(/\{[\s\S]*\}/);
  if (!m) throw new Error("не JSON");
  return JSON.parse(m[0]);
}

export async function makeQuest(
  loc: Location,
  type: TaskType,
  date: string,
  idx: number
): Promise<Quest | null> {
  try {
    const raw = await yandexChat(SYSTEM, userPrompt(loc, type));
    const q = parseJson(raw);
    if (!q.title || !q.story || !q.task?.text || !q.ending) return null;
    return {
      id: `${date}-${loc.id}-${idx}`,
      locationId: loc.id,
      locationName: loc.name,
      character: loc.character,
      image: loc.image,
      title: String(q.title),
      story: String(q.story),
      task: { type, text: String(q.task.text) },
      ending: String(q.ending),
    };
  } catch (e) {
    console.error("квест не сгенерился:", e);
    return null;
  }
}

function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export async function generateDayPool(date: string): Promise<Quest[]> {
  const order = [...shuffle(LOCATIONS), ...shuffle(LOCATIONS)];
  const out: Quest[] = [];
  for (let i = 0; i < DAY_PLAN.length; i += 8) {
    const batch = await Promise.all(
      DAY_PLAN.slice(i, i + 8).map((type, j) =>
        makeQuest(order[i + j], type, date, i + j)
      )
    );
    out.push(...(batch.filter((q) => q !== null) as Quest[]));
  }
  return out;
}
